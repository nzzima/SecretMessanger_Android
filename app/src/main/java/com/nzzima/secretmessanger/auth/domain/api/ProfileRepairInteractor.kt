package com.nzzima.secretmessanger.auth.domain.api

/**
 * Достройка регистрации, оборванной на полпути.
 *
 * Регистрация идёт тремя записями — аккаунт, логин в реестре, профиль, — и прерваться может
 * между ними: таймаутом отправки или отказом связи. Аккаунт в Firebase Auth при этом
 * остаётся, а логина и профиля у него нет.
 *
 * Такой аккаунт не просто выглядит пустым: публикация открытой половины ключа пишет
 * `users/{uid}` слиянием, а правило на этой коллекции требует в записи логин, занятый тем же
 * аккаунтом. Без профиля слияние проверку не проходит — и вход упирается в развилку ключа
 * навсегда. Поэтому достройка идёт **до** проверки ключа.
 */
interface ProfileRepairInteractor {

    /** Достроена ли регистрация аккаунта [uid]: есть ли у него профиль. */
    suspend fun isComplete(uid: String): Result<Boolean>

    /**
     * Достраивает регистрацию аккаунта [uid] под именем [login].
     *
     * Логин запрашивается заново, а не восстанавливается: реестр `logins` запрещает выборку
     * (`allow list: if false`), и узнать по идентификатору, какое имя было занято, нельзя.
     * Уже занятый этим же аккаунтом логин принимается — так закрывается обрыв, случившийся
     * между записью в реестр и записью профиля.
     */
    suspend fun complete(uid: String, login: String): Result<Unit>
}
