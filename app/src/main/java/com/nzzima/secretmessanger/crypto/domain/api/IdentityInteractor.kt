package com.nzzima.secretmessanger.crypto.domain.api

import com.nzzima.secretmessanger.crypto.domain.models.IdentityState

/**
 * Постоянный ключ аккаунта при входе.
 *
 * Правило одно: **публикация, затирающая чужую открытую половину, требует подтверждения;
 * любая другая идёт молча.**
 */
interface IdentityInteractor {

    /**
     * Приводит ключ аккаунта [uid] в рабочее состояние.
     *
     * Заводит ключ и публикует открытую половину, если затирать нечего. Возвращает
     * [IdentityState.NeedsConfirmation], не изменив ничего, если в профиле чужая половина.
     *
     * Отказ чтения профиля возвращается отказом: ключ при этом не публикуется.
     */
    suspend fun prepare(uid: String): Result<IdentityState>

    /**
     * Публикует свою открытую половину поверх чужой. Вызывается только после подтверждения.
     *
     * Если ключа на устройстве нет, заводит новый. Прежняя переписка аккаунта после этого
     * не открывается ни здесь, ни на устройстве, чья половина была затёрта.
     */
    suspend fun publishOverwriting(uid: String): Result<Unit>
}
