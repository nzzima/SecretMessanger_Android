package com.nzzima.secretmessanger.crypto.domain.api

/**
 * Постоянный ключ аккаунта на этом устройстве.
 *
 * Операции «взять» и «завести» разделены намеренно: заведение ключа публикует новую
 * открытую половину поверх прежней и делает прежнюю переписку нечитаемой, поэтому
 * происходить оно должно только по осознанному выбору, а не как побочный эффект чтения.
 *
 * Ключ хранится отдельно для каждого `uid`.
 */
interface IdentityKeyStore {

    /**
     * Приватная половина аккаунта [uid] — 32 байта, либо `null`, если её здесь нет.
     *
     * Ключ не создаётся ни при каких условиях.
     */
    fun existing(uid: String): ByteArray?

    /**
     * Заводит новую пару для аккаунта [uid] и сохраняет её, затирая прежнюю.
     *
     * @return приватная половина — 32 байта.
     */
    fun createNew(uid: String): ByteArray

    /** Забывает ключ аккаунта [uid]. Восстановить его после этого нечем. */
    fun forget(uid: String)
}
